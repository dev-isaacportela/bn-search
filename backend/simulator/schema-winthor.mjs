// add-001-jdbc-winthor.mjs; aqui consultam este schema, com os mesmos nomes e
// colunas, pelo dialeto Oracle -> SQLite (mysql-dialect.mjs). Estas tabelas
// NUNCA são criadas no banco do projeto.
//
// Só DDL e só as colunas que add-002-estoque.mjs lê. Um template literal por
// tabela, começando pela frase de criação idempotente (o leitor de schema.mjs
// é por texto). Definições copiadas do SGC 2 (p-novo-sgc), menos PCPEDC e
// PCPEDI, que são novas aqui (RN-009 — premissa a validar no ERP, T-016).

